fn main() {
    // Переменные и изменяемость.

    let mut x = 5; // Изменяемая переменная.
    println!("Значение x: {x}");
    x = 6;
    println!("Теперь x: {x}");

    let x = "Some string"; // Затенение x с изменением типа переменной.
    println!("x = {x}");

    // Скалярные типы данных.

    // Целые числа.
    let a: i32 = 42;
    let b: u8 = 255;
    let c: isize = -100;
    let hex = 0xff; // 255 в шестнадцатеричной
    let octal = 0o77; // 63 в восьмеричной
    let binary = 0b1111_0000; // 240 в двоичной
    let byte = b'A'; // 65 (байтовый литерал)

    // Числа с плавающей точкой.
    let pi: f64 = 3.14159265;
    let e = 2.71828; // тип f64 по умолчанию

    // Булев тип.
    let is_active: bool = true;
    let is_greater = 10 > 5; // true

    // Символьный тип.
    let c = 'z';
    let heart = '❤';
    let emoji = '🦀'; // да, краб -  символ Rust!

    // Составные типы.

    // Кортежи (tuples).
    let tup: (i32, f64, bool) = (500, 6.4, true);

    // Деструктуризация.
    let (x, y, z) = tup;
    println!("y = {}", y); // 6.4

    // Доступ по индексу через точку.
    let first = tup.0; // 500
    let second = tup.1; // 6.4

    // Массивы (arrays).
    let a = [1, 2, 3, 4, 5];
    let first = a[0]; // 1
    let second = a[1]; // 2

    // Явное указание типа и длины.
    let b: [i32; 5] = [1, 2, 3, 4, 5];

    // Массив из 5 элементов, все равны 3.
    let c = [3; 5]; // [3, 3, 3, 3, 3]

    // Преобразование строки в число.

    let s = "42";
    let n: i32 = s.parse::<i32>().unwrap();
    println!("Число: {}", n);

    let f: f64 = "3.14".parse::<f64>().unwrap();
    println!("Дробное: {}", f);

    // Арифметика и целочисленное деление.

    let a: i32 = 1 / 100; // a = 0, а не 0.01
    let b: i32 = 7 / 2; // b = 3, а не 3.5
    let r: i32 = 7 % 2; // r = 1 — остаток от деления

    // Если нужно дробное — приводите хотя бы один операнд к f64:
    let c: f64 = 1.0 / 100.0; // 0.01
    let d: f64 = 7.0 / 2.0; // 3.5
    let e: f64 = 1_f64 / 100.0; // 0.01

    println!("{} {} {} {} {} {}", a, b, r, c, d, e);

    // Константы.

    const MAX_POINTS: u32 = 100_000;
    const PI: f64 = 3.14159265358979;
}
